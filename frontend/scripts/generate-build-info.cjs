const fs = require('fs')
const path = require('path')
const childProcess = require('child_process')

const root = path.resolve(__dirname, '..')
const outDir = path.join(root, 'src', 'generated')
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'))

function exec(command) {
  try {
    return childProcess.execSync(command, { cwd: path.resolve(root, '..'), stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim()
  } catch {
    return 'unknown'
  }
}

const info = {
  version: pkg.version || '0.0.0',
  builtAt: new Date().toISOString(),
  gitCommit: exec('git rev-parse --short HEAD'),
  nodeVersion: process.version,
}

fs.mkdirSync(outDir, { recursive: true })
const content = `// Auto-generated by frontend/scripts/generate-build-info.cjs. Do not edit by hand.\nexport const FRONTEND_BUILD_INFO = ${JSON.stringify(info, null, 2)} as const\n`
fs.writeFileSync(path.join(outDir, 'buildInfo.ts'), content)
console.log(`[OK] wrote src/generated/buildInfo.ts (${info.builtAt})`)
